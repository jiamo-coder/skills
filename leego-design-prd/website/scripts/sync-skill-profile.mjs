import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const websiteRoot = path.resolve(scriptDirectory, '..');
const skillRoot = path.resolve(websiteRoot, '..');
const skillPath = path.join(skillRoot, 'SKILL.md');
const ledgerPath = path.join(skillRoot, 'references', 'learning-ledger.md');
const profilePath = path.join(websiteRoot, 'src', 'content', 'capability-profile.ts');
const outputPath = path.join(websiteRoot, 'src', 'content', 'profile-stats.generated.ts');
const packageJsonPath = path.join(websiteRoot, 'package.json');
const releaseVersionPath = path.join(websiteRoot, 'release-version.json');
const checkOnly = process.argv.includes('--check');

const [skill, ledger, profile, packageJsonSource, releaseVersionSource] = await Promise.all([
  readFile(skillPath, 'utf8'),
  readFile(ledgerPath, 'utf8'),
  readFile(profilePath, 'utf8'),
  readFile(packageJsonPath, 'utf8'),
  readFile(releaseVersionPath, 'utf8'),
]);

const frontmatter = skill.match(/^---\n([\s\S]*?)\n---/)?.[1];
const skillVersion = frontmatter?.match(
  /^metadata:\s*\n(?: {2}[^\n]*\n)*? {2}version:\s*["']?(\d+\.\d+\.\d+)["']?\s*$/m,
)?.[1];
if (!skillVersion) throw new Error('SKILL.md metadata.version 缺失或不是三段式 SemVer');

const packageVersion = JSON.parse(packageJsonSource).version;
const releaseVersion = JSON.parse(releaseVersionSource).semver;
if (packageVersion !== skillVersion || releaseVersion !== skillVersion) {
  throw new Error(
    `版本不一致：Skill=${skillVersion}，package=${packageVersion}，release=${releaseVersion}`,
  );
}

const entries = [...ledger.matchAll(/^## (GL-\d{3}) .+?\n([\s\S]*?)(?=^## GL-|(?![\s\S]))/gm)].map(
  ([, id, body]) => {
    const status = body.match(/^- 状态：(.+)$/m)?.[1]?.trim();
    if (!status) throw new Error(`${id} 缺少状态字段`);
    return { id, status };
  },
);

if (entries.length === 0) throw new Error('学习账本中没有可识别的 GL 条目');

const learningRevision = Math.max(
  ...entries.map((entry) => Number(entry.id.replace('GL-', ''))),
);

const knownIds = new Set(entries.map((entry) => entry.id));
const referencedIds = new Set(profile.match(/GL-\d{3}/g) ?? []);
const missingIds = [...referencedIds].filter((id) => !knownIds.has(id));

if (missingIds.length > 0) {
  throw new Error(`能力档案引用了不存在的学习条目：${missingIds.join(', ')}`);
}

const counts = {
  verified: entries.filter((entry) => entry.status === '已验证方法').length,
  pending: entries.filter((entry) => entry.status === '待验证经验').length,
  conflicting: entries.filter((entry) => entry.status === '存在冲突').length,
  retired: entries.filter((entry) => entry.status === '已淘汰').length,
};

const verifiedAt = new Intl.DateTimeFormat('en-CA', {
  timeZone: 'Asia/Shanghai',
  year: 'numeric',
  month: '2-digit',
  day: '2-digit',
}).format(new Date());

const generated = `// Generated by scripts/sync-skill-profile.mjs. Do not edit by hand.\nexport const profileStats = {\n  skillVersion: '${skillVersion}',\n  learningRevision: ${learningRevision},\n  total: ${entries.length},\n  verified: ${counts.verified},\n  pending: ${counts.pending},\n  conflicting: ${counts.conflicting},\n  retired: ${counts.retired},\n  verifiedAt: '${verifiedAt}',\n} as const;\n`;

if (checkOnly) {
  const current = await readFile(outputPath, 'utf8');
  if (current !== generated) {
    throw new Error('公开能力统计已过期，请运行 npm run content:sync');
  }
  console.log(
    `能力档案校验通过：Skill v${skillVersion}，L${learningRevision}，${entries.length} 条学习记录，${referencedIds.size} 个引用`,
  );
} else {
  await writeFile(outputPath, generated, 'utf8');
  console.log(
    `已同步能力档案：Skill v${skillVersion}，L${learningRevision}，核验日期 ${verifiedAt}`,
  );
}
